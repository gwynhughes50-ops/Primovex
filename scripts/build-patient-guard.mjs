// Bundles src/ai/guard/patientGuard.js into functions/services/patientGuard.cjs so the server applies exactly the same patient-identity rules as the app.
//   node scripts/build-patient-guard.mjs          writes the file
//   node scripts/build-patient-guard.mjs --check  fails if the file is out of date (a test runs this)
import { build } from "esbuild";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const OUT = new URL("../functions/services/patientGuard.cjs", import.meta.url);
const result = await build({
  entryPoints: [new URL("../src/ai/guard/patientGuard.js", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")],
  bundle: true, platform: "node", format: "cjs", write: false, legalComments: "none", target: "node22",
  banner: { js: "// GENERATED by scripts/build-patient-guard.mjs from src/ai/guard/patientGuard.js. Do not edit: change the source and run `npm run build:patient-guard`." },
});
const text = result.outputFiles[0].text.replace(/\r\n/g, "\n");

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== text) { console.error("functions/services/patientGuard.cjs is out of date. Run: npm run build:patient-guard"); process.exit(1); }
  console.log("ok  the server's copy of the patient-identity guard is up to date");
} else {
  writeFileSync(OUT, text);
  console.log(`written ${text.length} bytes`);
}
