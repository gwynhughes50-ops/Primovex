// Bundles src/modules/rota/rotaCore.js into functions/services/rotaCore.cjs so the server uses exactly the same rota logic as the app.
//   node scripts/build-rota-core.mjs          writes the file
//   node scripts/build-rota-core.mjs --check  fails if the file is out of date (a test runs this)
import { build } from "esbuild";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const OUT = new URL("../functions/services/rotaCore.cjs", import.meta.url);
const result = await build({
  entryPoints: [new URL("../src/modules/rota/rotaCore.js", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")],
  bundle: true, platform: "node", format: "cjs", write: false, legalComments: "none", target: "node22",
  banner: { js: "// GENERATED by scripts/build-rota-core.mjs from src/modules/rota/rotaCore.js. Do not edit: change the source and run `npm run build:rota-core`.\n/* eslint-disable */" },
});
const text = result.outputFiles[0].text.replace(/\r\n/g, "\n");

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== text) { console.error("functions/services/rotaCore.cjs is out of date. Run: npm run build:rota-core"); process.exit(1); }
  console.log("ok  the server's copy of the rota logic is up to date");
} else {
  writeFileSync(OUT, text);
  console.log(`written ${text.length} bytes`);
}
